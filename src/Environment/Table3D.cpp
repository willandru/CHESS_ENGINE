#include "Table3D.h"

Table3D::Table3D()
{
}



//====================================================
// INITIALIZATION
//====================================================

bool Table3D::load()
{

    //------------------------------------------------
    // LOAD GLB MODEL
    //------------------------------------------------

    if(
        !loadGLB(
            "Assets/Environment/Table2.glb"
        )
    )
    {
        return false;
    }



    //------------------------------------------------
    // TRANSFORM
    //------------------------------------------------

    setPosition({
        0.0f,
        0.0f,
        0.0f
    });


    setRotation({
        0.0f,
        0.0f,
        0.0f
    });


    setScale({
        1.0f,
        1.0f,
        1.0f
    });



    //------------------------------------------------
    // MATERIAL
    //------------------------------------------------

    setColor({
        1.0f,
        1.0f,
        1.0f
    });



    return true;

}